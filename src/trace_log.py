"""Standard CAN traces: every frame on the wire, RX and own TX (TODO 5.9).

The own frames are the controller's echoes (`receive_own_messages=True`), so a
trace holds what really reached the bus, with the PCAN hardware timestamps —
not what was queued.
"""

import csv
import os
from datetime import datetime, timedelta, timezone

import can
from can.io.asc import ASCWriter
from can.io.blf import BLFWriter
from can.io.canutils import CanutilsLogWriter
from can.util import len2dlc

# Extension -> file-dialog label. ".csv" stays CANino's own RX statistics log.
TRACE_FORMATS = {
    ".trc": "PCAN-View trace",
    ".asc": "Vector ASCII trace",
    ".blf": "Vector binary trace",
    ".log": "candump log (Linux can-utils)",
}

# OLE Automation date epoch used by $STARTTIME
_OLE_EPOCH = datetime(1899, 12, 30, tzinfo=timezone.utc)


class TrcWriter:
    """PEAK TRC 2.1 writer (the format PCAN-View saves).

    python-can's TRCWriter drops every CAN FD frame and has no event lines,
    so this one is written here. Same column layout as PCAN-View: message
    number from 1, time offset in ms (µs resolution), type DT / FD / FB, bus,
    ID (4 hex digits standard, 8 extended), Rx/Tx, DLC code, data.
    $STARTTIME is written in UTC, as python-can's TRCReader reads it back.
    """

    def __init__(self, path, channel: int = 1):
        self.file = open(path, "w", encoding="ascii", newline="\r\n")
        self.path = os.path.abspath(path)
        self.channel = channel
        self.count = 0
        self.start = None

    def _header(self, timestamp: float):
        self.start = timestamp
        start = datetime.fromtimestamp(timestamp, timezone.utc)
        days = (start - _OLE_EPOCH) / timedelta(days=1)
        local = datetime.fromtimestamp(timestamp).strftime("%d.%m.%Y %H:%M:%S.%f")
        self.file.write(
            ";$FILEVERSION=2.1\n"
            f";$STARTTIME={days!r}\n"  # full precision: ~1 µs
            ";$COLUMNS=N,O,T,B,I,d,R,L,D\n"
            ";\n"
            f";   {self.path}\n"
            ";\n"
            f";   Start time: {local} (local)\n"
            ";   Generated by CANino App\n"
            ";-------------------------------------------------------------------------------\n"
            ";   Message   Time    Type    ID     Rx/Tx\n"
            ";   Number    Offset  |  Bus  [hex]  |  Reserved\n"
            ";   |         [ms]    |  |    |      |  |  Data Length Code\n"
            ";   |         |       |  |    |      |  |  |    Data [hex] ...\n"
            ";   |         |       |  |    |      |  |  |    |\n"
            ";---+-- ------+------ +- +- --+----- +- +- +--- +- -- -- -- -- -- -- --\n"
        )

    def on_message_received(self, msg: can.Message):
        if self.start is None:
            self._header(msg.timestamp)
        self.count += 1
        if msg.is_fd:
            kind = "FB" if msg.bitrate_switch else "FD"
        else:
            kind = "DT"
        frame_id = (
            f"{msg.arbitration_id:08X}"
            if msg.is_extended_id
            else f"{msg.arbitration_id:04X}"
        )
        data = " ".join(f"{b:02X}" for b in msg.data)
        line = (
            f"{self.count:>7} {(msg.timestamp - self.start) * 1000:13.3f} {kind} "
            f"{self.channel:>2} {frame_id:>8} {'Rx' if msg.is_rx else 'Tx'} - "
            f"{len2dlc(len(msg.data)):>2}   {data}"
        )
        self.file.write(line.rstrip() + "\n")

    def log_comment(self, marker_ts: float, text: str):
        """A `;` comment line, positioned in the frame stream (TODO 13.2).
        TRC readers skip it; the sidecar holds the machine-readable label."""
        if self.start is None:
            self._header(marker_ts)
        self.file.write(f";LABEL {(marker_ts - self.start) * 1000:.3f} {text}\n")

    def stop(self):
        self.file.close()


def _open_writer(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == ".trc":
        return TrcWriter(path)
    if ext == ".asc":
        return ASCWriter(path)
    if ext == ".blf":
        return BLFWriter(path)
    if ext == ".log":
        return CanutilsLogWriter(path, channel="can0")
    raise ValueError(f"Unsupported trace format: {ext or path}")


def label_path(trace_path: str) -> str:
    """Sidecar next to the trace: trace.trc -> trace.labels.csv."""
    root, _ = os.path.splitext(trace_path)
    return root + ".labels.csv"


class TraceLog:
    """One open trace file; written from the GUI thread (RX drain).

    Attack windows are tagged two ways (TODO 13.2): an in-trace marker where
    the format carries events (`.trc` comment, `.asc`/`.blf` log event), and an
    authoritative sidecar `<name>.labels.csv` with the wall-clock start/stop of
    each attack. The sidecar is the format-independent artifact IDS training
    joins against the frames; the in-trace marker keeps the trace self-describing.
    """

    def __init__(self, path):
        self.path = path
        self.writer = _open_writer(path)
        self.frames = 0
        self.labels = 0
        self._last_ts = None  # last frame's hardware time: positions markers
        self._label_file = None
        self._label_writer = None

    def write(self, frame_id, data, is_fd, timestamp, is_ext, brs, is_echo):
        self.writer.on_message_received(
            can.Message(
                timestamp=timestamp,
                arbitration_id=frame_id,
                is_extended_id=is_ext,
                is_fd=is_fd,
                bitrate_switch=bool(is_fd and brs),
                is_rx=not is_echo,
                data=data,
                check=False,
            )
        )
        self._last_ts = timestamp
        self.frames += 1

    def log_label(self, timestamp, action, mode, label):
        """Tag an attack boundary. `timestamp` is the wall clock (time.time);
        the sidecar keeps it, the in-trace marker is placed just after the last
        frame so it stays monotonic with the hardware-clock frame stream (the
        two clocks differ by a documented constant offset on PCAN)."""
        text = f"{action} {mode} {label}"
        marker_ts = self._last_ts if self._last_ts is not None else timestamp
        w = self.writer
        if isinstance(w, TrcWriter):
            w.log_comment(marker_ts, text)
        elif hasattr(w, "log_event"):  # ASC, BLF
            w.log_event(f"CANino LABEL {text}", marker_ts)
        # CanutilsLogWriter has no event line: the sidecar is the only record
        if self._label_writer is None:
            self._label_file = open(
                label_path(self.path), "w", newline="", encoding="utf-8"
            )
            self._label_writer = csv.writer(self._label_file)
            self._label_writer.writerow(
                ["Timestamp", "Epoch", "Action", "Mode", "Label"]
            )
        self._label_writer.writerow(
            [
                datetime.fromtimestamp(timestamp).strftime("%Y-%m-%dT%H:%M:%S.%f"),
                f"{timestamp:.6f}",
                action,
                mode,
                label,
            ]
        )
        self._label_file.flush()
        self.labels += 1

    def flush(self):
        """Text traces: to disk after every drain, like the CSV. A BLF file
        keeps its buffer — flushing would cut a compressed container per drain."""
        if not isinstance(self.writer, BLFWriter):
            self.writer.file.flush()

    def close(self):
        self.writer.stop()
        if self._label_file is not None:
            self._label_file.close()
            self._label_file = None
            self._label_writer = None

    @staticmethod
    def is_trace(path) -> bool:
        return os.path.splitext(path or "")[1].lower() in TRACE_FORMATS
